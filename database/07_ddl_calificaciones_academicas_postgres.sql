-- Calificaciones y progreso estimado por estudiante, materia y grupo.
-- Requiere 05_ddl_tareas_academicas_postgres.sql y sus asignaciones.

CREATE TABLE IF NOT EXISTS planes_evaluacion (
  id_plan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo BIGINT NOT NULL,
  id_materia BIGINT NOT NULL,
  id_docente BIGINT NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_plan_grupo_materia UNIQUE (id_grupo, id_materia),
  CONSTRAINT uq_plan_id_docente UNIQUE (id_plan, id_docente),
  CONSTRAINT fk_plan_grupo_materia_docente
    FOREIGN KEY (id_grupo, id_materia, id_docente)
    REFERENCES grupo_materias_docentes(id_grupo, id_materia, id_docente)
);

CREATE TABLE IF NOT EXISTS evaluaciones_academicas (
  id_evaluacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_plan BIGINT NOT NULL REFERENCES planes_evaluacion(id_plan)
    ON DELETE CASCADE,
  nombre VARCHAR(120) NOT NULL,
  peso_porcentual NUMERIC(5, 2) NOT NULL
    CHECK (peso_porcentual > 0 AND peso_porcentual <= 100),
  creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_evaluacion_plan_nombre UNIQUE (id_plan, nombre),
  CONSTRAINT uq_evaluacion_plan_contexto UNIQUE (id_evaluacion, id_plan)
);

CREATE INDEX IF NOT EXISTS ix_evaluaciones_plan
  ON evaluaciones_academicas(id_plan);

CREATE TABLE IF NOT EXISTS calificaciones_academicas (
  id_evaluacion BIGINT NOT NULL,
  id_plan BIGINT NOT NULL,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario)
    ON DELETE CASCADE,
  calificacion NUMERIC(5, 2) NOT NULL
    CHECK (calificacion >= 0 AND calificacion <= 100),
  calificada_por BIGINT NOT NULL,
  calificada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_evaluacion, id_usuario),
  CONSTRAINT fk_calificacion_evaluacion_plan
    FOREIGN KEY (id_evaluacion, id_plan)
    REFERENCES evaluaciones_academicas(id_evaluacion, id_plan)
    ON DELETE CASCADE,
  CONSTRAINT fk_calificacion_docente_plan
    FOREIGN KEY (id_plan, calificada_por)
    REFERENCES planes_evaluacion(id_plan, id_docente)
);

CREATE INDEX IF NOT EXISTS ix_calificaciones_usuario_plan
  ON calificaciones_academicas(id_usuario, id_plan);

CREATE OR REPLACE FUNCTION validar_peso_evaluacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_peso_existente NUMERIC(6, 2);
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.id_plan <> OLD.id_plan THEN
    RAISE EXCEPTION
      'No se puede mover una evaluación a otro plan; elimínala y créala en el plan correcto.';
  END IF;

  PERFORM 1
  FROM planes_evaluacion
  WHERE id_plan = NEW.id_plan
  FOR UPDATE;

  SELECT COALESCE(SUM(peso_porcentual), 0)
  INTO v_peso_existente
  FROM evaluaciones_academicas
  WHERE id_plan = NEW.id_plan
    AND id_evaluacion IS DISTINCT FROM NEW.id_evaluacion;

  IF v_peso_existente + NEW.peso_porcentual > 100 THEN
    RAISE EXCEPTION
      'La suma de ponderaciones de un plan no puede superar 100%%.';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_peso_evaluacion
  ON evaluaciones_academicas;

CREATE TRIGGER trg_validar_peso_evaluacion
  BEFORE INSERT OR UPDATE OF id_plan, peso_porcentual
  ON evaluaciones_academicas
  FOR EACH ROW
  EXECUTE FUNCTION validar_peso_evaluacion();

CREATE OR REPLACE FUNCTION validar_calificacion_academica()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM planes_evaluacion p
    JOIN grupos g ON g.id_grupo = p.id_grupo
    JOIN usuarios u
      ON u.id_usuario = NEW.id_usuario
      AND u.id_grupo = g.id_grupo
    JOIN usuario_roles ur ON ur.id_usuario = u.id_usuario
    JOIN roles r
      ON r.id_rol = ur.id_rol
      AND r.codigo = 'ESTUDIANTE'
    JOIN docentes d
      ON d.id_docente = NEW.calificada_por
      AND d.id_usuario IS NOT NULL
    JOIN usuario_roles docente_ur
      ON docente_ur.id_usuario = d.id_usuario
    JOIN roles docente_r
      ON docente_r.id_rol = docente_ur.id_rol
      AND docente_r.codigo = 'DOCENTE'
    WHERE p.id_plan = NEW.id_plan
  ) THEN
    RAISE EXCEPTION
      'La calificación requiere un estudiante del grupo y un docente asignado con rol DOCENTE.';
  END IF;

  NEW.calificada_en := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_calificacion_academica
  ON calificaciones_academicas;

CREATE TRIGGER trg_validar_calificacion_academica
  BEFORE INSERT OR UPDATE OF id_evaluacion, id_plan, id_usuario,
    calificacion, calificada_por
  ON calificaciones_academicas
  FOR EACH ROW
  EXECUTE FUNCTION validar_calificacion_academica();

CREATE OR REPLACE VIEW vista_evaluaciones_estudiante AS
SELECT u.id_usuario,
       c.codigo AS codigo_carrera,
       g.id_grupo,
       g.numero_semestre,
       m.id_materia,
       m.codigo AS codigo_materia,
       m.nombre AS materia,
       p.id_plan,
       e.id_evaluacion,
       e.nombre AS entregable,
       e.peso_porcentual,
       cal.calificacion,
       cal.calificada_en
FROM usuarios u
JOIN grupos g ON g.id_grupo = u.id_grupo
JOIN carreras c ON c.id_carrera = g.id_carrera
JOIN planes_evaluacion p ON p.id_grupo = g.id_grupo
JOIN materias m ON m.id_materia = p.id_materia
JOIN evaluaciones_academicas e ON e.id_plan = p.id_plan
LEFT JOIN calificaciones_academicas cal
  ON cal.id_evaluacion = e.id_evaluacion
  AND cal.id_plan = p.id_plan
  AND cal.id_usuario = u.id_usuario
WHERE EXISTS (
  SELECT 1
  FROM usuario_roles ur
  JOIN roles r ON r.id_rol = ur.id_rol
  WHERE ur.id_usuario = u.id_usuario
    AND r.codigo = 'ESTUDIANTE'
);

CREATE OR REPLACE VIEW vista_progreso_calificaciones_estudiante AS
SELECT v.id_usuario,
       v.codigo_carrera,
       v.id_grupo,
       v.numero_semestre,
       v.id_materia,
       v.id_plan,
       v.codigo_materia,
       v.materia,
       ROUND(SUM(v.peso_porcentual), 2) AS ponderacion_total,
       ROUND(
         COALESCE(
           SUM(v.peso_porcentual) FILTER (
             WHERE v.calificacion IS NOT NULL
           ),
           0
         ),
         2
       ) AS progreso_curso,
       COUNT(v.id_evaluacion) AS entregables_totales,
       COUNT(v.calificacion) AS entregables_calificados,
       CASE
         WHEN SUM(v.peso_porcentual) = 100
           AND SUM(v.peso_porcentual) FILTER (
             WHERE v.calificacion IS NOT NULL
           ) > 0
         THEN ROUND(
           SUM(v.calificacion * v.peso_porcentual) FILTER (
             WHERE v.calificacion IS NOT NULL
           ) / SUM(v.peso_porcentual) FILTER (
             WHERE v.calificacion IS NOT NULL
           ),
           2
         )
         ELSE NULL
       END AS promedio_estimado,
       (SUM(v.peso_porcentual) = 100) AS plan_completo,
       (
         SUM(v.peso_porcentual) = 100
         AND SUM(v.peso_porcentual) FILTER (
           WHERE v.calificacion IS NOT NULL
         ) > 0
       ) AS es_estimacion,
       100::NUMERIC(5, 2) AS escala_maxima
FROM vista_evaluaciones_estudiante v
GROUP BY v.id_usuario,
         v.codigo_carrera,
         v.id_grupo,
         v.numero_semestre,
         v.id_materia,
         v.id_plan,
         v.codigo_materia,
         v.materia;

COMMENT ON TABLE planes_evaluacion IS
  'Plan de ponderación de una materia y grupo; el docente debe tener asignación vigente.';

COMMENT ON TABLE evaluaciones_academicas IS
  'Entregables con ponderación porcentual; la suma se limita a 100 y debe completar 100 para estimar el promedio.';

COMMENT ON TABLE calificaciones_academicas IS
  'Calificaciones en escala de 0 a 100 capturadas por el docente asignado.';

COMMENT ON VIEW vista_progreso_calificaciones_estudiante IS
  'Promedio ponderado estimado normalizado sobre evaluaciones calificadas; progreso es el porcentaje ponderado con calificación.';
