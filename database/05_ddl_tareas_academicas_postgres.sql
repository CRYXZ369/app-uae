-- Tareas, progreso individual y notificaciones académicas.
-- Requiere 01_ddl_app_unificada_uae_postgres.sql,
-- 03_ddl_academico_postgres.sql y 04_dml_academico_demo_postgres.sql.

CREATE TABLE IF NOT EXISTS grupo_materias_docentes (
  id_grupo BIGINT NOT NULL,
  id_carrera BIGINT NOT NULL,
  numero_semestre SMALLINT NOT NULL,
  id_materia BIGINT NOT NULL,
  id_docente BIGINT NOT NULL REFERENCES docentes(id_docente),
  CONSTRAINT pk_grupo_materia_docente
    PRIMARY KEY (id_grupo, id_materia),
  CONSTRAINT uq_grupo_materia_docente_contexto
    UNIQUE (id_grupo, id_materia, id_docente),
  CONSTRAINT fk_gmd_grupo_contexto
    FOREIGN KEY (id_grupo, id_carrera, numero_semestre)
    REFERENCES grupos(id_grupo, id_carrera, numero_semestre)
    ON DELETE CASCADE,
  CONSTRAINT fk_gmd_materia_contexto
    FOREIGN KEY (id_materia, id_carrera, numero_semestre)
    REFERENCES materias(id_materia, id_carrera, numero_semestre)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tareas_academicas (
  id_tarea BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_demo VARCHAR(48) UNIQUE,
  id_grupo BIGINT NOT NULL,
  id_materia BIGINT NOT NULL,
  id_docente BIGINT NOT NULL,
  titulo VARCHAR(160) NOT NULL,
  descripcion TEXT NOT NULL,
  fecha_entrega TIMESTAMPTZ NOT NULL,
  prioridad VARCHAR(10) NOT NULL
    CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
  creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_tarea_id_grupo UNIQUE (id_tarea, id_grupo),
  CONSTRAINT fk_tarea_grupo_materia_docente
    FOREIGN KEY (id_grupo, id_materia, id_docente)
    REFERENCES grupo_materias_docentes(id_grupo, id_materia, id_docente)
);

CREATE INDEX IF NOT EXISTS ix_tareas_grupo_fecha
  ON tareas_academicas(id_grupo, fecha_entrega);

CREATE INDEX IF NOT EXISTS ix_tareas_docente_creada
  ON tareas_academicas(id_docente, creada_en DESC);

CREATE TABLE IF NOT EXISTS entregas_tareas (
  id_tarea BIGINT NOT NULL,
  id_grupo BIGINT NOT NULL,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  estado VARCHAR(16) NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado IN ('PENDIENTE', 'EN_PROGRESO', 'ENTREGADA')),
  contenido_entrega TEXT,
  fecha_entregada TIMESTAMPTZ,
  actualizada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_tarea, id_usuario),
  CONSTRAINT fk_entrega_tarea_grupo
    FOREIGN KEY (id_tarea, id_grupo)
    REFERENCES tareas_academicas(id_tarea, id_grupo)
    ON DELETE CASCADE,
  CONSTRAINT chk_entrega_fecha_estado
    CHECK (
      (estado = 'ENTREGADA' AND fecha_entregada IS NOT NULL)
      OR
      (estado <> 'ENTREGADA' AND fecha_entregada IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_entregas_usuario_estado
  ON entregas_tareas(id_usuario, estado);

CREATE TABLE IF NOT EXISTS notificaciones (
  id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  id_tarea BIGINT REFERENCES tareas_academicas(id_tarea) ON DELETE CASCADE,
  tipo VARCHAR(30) NOT NULL
    CHECK (tipo IN ('TAREA_CREADA', 'TAREA_PROXIMA', 'SISTEMA')),
  titulo VARCHAR(160) NOT NULL,
  mensaje TEXT NOT NULL,
  creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  leida_en TIMESTAMPTZ,
  CONSTRAINT uq_notificacion_tarea_usuario_tipo
    UNIQUE (id_usuario, id_tarea, tipo)
);

CREATE INDEX IF NOT EXISTS ix_notificaciones_usuario_recientes
  ON notificaciones(id_usuario, creada_en DESC);

CREATE OR REPLACE FUNCTION validar_entrega_tarea_estudiante()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM usuarios u
    WHERE u.id_usuario = NEW.id_usuario
      AND u.id_grupo = NEW.id_grupo
      AND EXISTS (
        SELECT 1
        FROM usuario_roles ur
        JOIN roles r ON r.id_rol = ur.id_rol
        WHERE ur.id_usuario = u.id_usuario
          AND r.codigo = 'ESTUDIANTE'
      )
  ) THEN
    RAISE EXCEPTION
      'El usuario no es estudiante del grupo asignado a esta tarea.';
  END IF;

  NEW.actualizada_en := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_entrega_tarea_estudiante
  ON entregas_tareas;

CREATE TRIGGER trg_validar_entrega_tarea_estudiante
  BEFORE INSERT OR UPDATE OF id_tarea, id_grupo, id_usuario, estado
  ON entregas_tareas
  FOR EACH ROW
  EXECUTE FUNCTION validar_entrega_tarea_estudiante();

CREATE OR REPLACE FUNCTION notificar_tarea_al_grupo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.codigo_demo IS NOT NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO notificaciones (id_usuario, id_tarea, tipo, titulo, mensaje)
  SELECT u.id_usuario,
         NEW.id_tarea,
         'TAREA_CREADA',
         'Nueva tarea asignada',
         'Se asignó la tarea: ' || NEW.titulo
  FROM usuarios u
  WHERE u.id_grupo = NEW.id_grupo
    AND EXISTS (
      SELECT 1
      FROM usuario_roles ur
      JOIN roles r ON r.id_rol = ur.id_rol
      WHERE ur.id_usuario = u.id_usuario
        AND r.codigo = 'ESTUDIANTE'
    )
  ON CONFLICT (id_usuario, id_tarea, tipo) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_notificar_tarea_al_grupo
  ON tareas_academicas;

CREATE TRIGGER trg_notificar_tarea_al_grupo
  AFTER INSERT
  ON tareas_academicas
  FOR EACH ROW
  EXECUTE FUNCTION notificar_tarea_al_grupo();

CREATE OR REPLACE VIEW vista_tareas_estudiante AS
SELECT u.id_usuario,
       c.codigo AS codigo_carrera,
       g.id_grupo,
       g.nombre AS grupo,
       g.numero_semestre,
       t.id_tarea,
       t.codigo_demo,
       t.titulo,
       t.descripcion,
       m.codigo AS codigo_materia,
       m.nombre AS materia,
       d.nombre_completo AS docente,
       t.fecha_entrega,
       t.prioridad,
       CASE
         WHEN e.estado = 'ENTREGADA' THEN 'ENTREGADA'
         WHEN t.fecha_entrega < now() THEN 'VENCIDA'
         WHEN e.estado = 'EN_PROGRESO' THEN 'EN_PROGRESO'
         ELSE 'PENDIENTE'
       END AS estado,
       e.fecha_entregada,
       (e.estado = 'ENTREGADA' AND e.fecha_entregada > t.fecha_entrega)
         AS entrega_tardia
FROM usuarios u
JOIN grupos g ON g.id_grupo = u.id_grupo
JOIN carreras c ON c.id_carrera = g.id_carrera
JOIN tareas_academicas t ON t.id_grupo = g.id_grupo
JOIN materias m ON m.id_materia = t.id_materia
JOIN docentes d ON d.id_docente = t.id_docente
LEFT JOIN entregas_tareas e
  ON e.id_tarea = t.id_tarea
  AND e.id_usuario = u.id_usuario
WHERE EXISTS (
  SELECT 1
  FROM usuario_roles ur
  JOIN roles r ON r.id_rol = ur.id_rol
  WHERE ur.id_usuario = u.id_usuario
    AND r.codigo = 'ESTUDIANTE'
);

CREATE OR REPLACE VIEW vista_tareas_proximas_estudiante AS
SELECT *
FROM vista_tareas_estudiante
WHERE fecha_entrega >= now()
  AND fecha_entrega <= now() + INTERVAL '7 days'
  AND estado IN ('PENDIENTE', 'EN_PROGRESO');

COMMENT ON TABLE tareas_academicas IS
  'Tareas asignadas a una materia y grupo; su docente debe estar asignado a esa materia.';

COMMENT ON TABLE entregas_tareas IS
  'Estado de cada tarea por estudiante; VENCIDA se deriva de fecha_entrega en la vista.';

COMMENT ON VIEW vista_tareas_estudiante IS
  'Vista lógica por usuario; la API debe filtrar id_usuario usando la identidad autenticada.';

COMMENT ON VIEW vista_tareas_proximas_estudiante IS
  'Tareas pendientes o en progreso con vencimiento en los próximos siete días.';
