-- Compatibilidad no destructiva entre el esquema inicial de Supabase y el
-- modelo academico del repositorio. Conserva las columnas y relaciones
-- existentes (clave, codigo_grupo, semestre, turno y periodo_escolar).
-- Aplicar despues de 01_ddl_app_unificada_uae_postgres.sql y antes de 03.

BEGIN;

-- Estos CREATE cubren tambien instalaciones nuevas; en Supabase existente no
-- reemplazan las tablas ni modifican sus identificadores.
CREATE TABLE IF NOT EXISTS carreras (
  id_carrera BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave VARCHAR(30) NOT NULL UNIQUE,
  codigo VARCHAR(30),
  nombre VARCHAR(150) NOT NULL UNIQUE,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE carreras ADD COLUMN IF NOT EXISTS clave VARCHAR(30);
ALTER TABLE carreras ADD COLUMN IF NOT EXISTS codigo VARCHAR(30);

UPDATE carreras
SET codigo = COALESCE(codigo, clave),
    clave = COALESCE(clave, codigo);

ALTER TABLE carreras ALTER COLUMN clave SET NOT NULL;
ALTER TABLE carreras ALTER COLUMN codigo SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_carreras_codigo ON carreras (codigo);

CREATE TABLE IF NOT EXISTS grupos (
  id_grupo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_carrera BIGINT NOT NULL REFERENCES carreras(id_carrera),
  codigo_grupo VARCHAR(30) NOT NULL,
  semestre SMALLINT NOT NULL CHECK (semestre BETWEEN 1 AND 12),
  turno VARCHAR(30) NOT NULL DEFAULT 'MATUTINO',
  periodo_escolar VARCHAR(30) NOT NULL DEFAULT 'DEMO',
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  codigo VARCHAR(30),
  numero_semestre SMALLINT,
  nombre VARCHAR(30)
);

ALTER TABLE grupos ADD COLUMN IF NOT EXISTS codigo_grupo VARCHAR(30);
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS semestre SMALLINT;
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS turno VARCHAR(30) NOT NULL DEFAULT 'MATUTINO';
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS periodo_escolar VARCHAR(30) NOT NULL DEFAULT 'DEMO';
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS codigo VARCHAR(30);
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS numero_semestre SMALLINT;
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS nombre VARCHAR(30);

UPDATE grupos
SET codigo = COALESCE(codigo, codigo_grupo),
    codigo_grupo = COALESCE(codigo_grupo, codigo),
    numero_semestre = COALESCE(numero_semestre, semestre),
    semestre = COALESCE(semestre, numero_semestre),
    nombre = COALESCE(nombre, codigo_grupo, codigo);

ALTER TABLE grupos ALTER COLUMN codigo SET NOT NULL;
ALTER TABLE grupos ALTER COLUMN codigo_grupo SET NOT NULL;
ALTER TABLE grupos ALTER COLUMN numero_semestre SET NOT NULL;
ALTER TABLE grupos ALTER COLUMN semestre SET NOT NULL;
ALTER TABLE grupos ALTER COLUMN nombre SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_grupos_codigo_periodo
  ON grupos (id_carrera, numero_semestre, codigo, periodo_escolar);
CREATE UNIQUE INDEX IF NOT EXISTS uq_grupos_contexto_academico
  ON grupos (id_grupo, id_carrera, numero_semestre);

CREATE OR REPLACE FUNCTION sincronizar_codigo_carrera()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.codigo := COALESCE(NEW.codigo, NEW.clave);
    NEW.clave := COALESCE(NEW.clave, NEW.codigo);
  ELSIF NEW.codigo IS DISTINCT FROM OLD.codigo THEN
    NEW.clave := NEW.codigo;
  ELSE
    NEW.codigo := NEW.clave;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sincronizar_codigo_carrera ON carreras;
CREATE TRIGGER trg_sincronizar_codigo_carrera
  BEFORE INSERT OR UPDATE ON carreras
  FOR EACH ROW EXECUTE FUNCTION sincronizar_codigo_carrera();

CREATE OR REPLACE FUNCTION sincronizar_grupo_compatibilidad()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.codigo := COALESCE(NEW.codigo, NEW.codigo_grupo);
    NEW.codigo_grupo := COALESCE(NEW.codigo_grupo, NEW.codigo);
    NEW.numero_semestre := COALESCE(NEW.numero_semestre, NEW.semestre);
    NEW.semestre := COALESCE(NEW.semestre, NEW.numero_semestre);
  ELSE
    IF NEW.codigo IS DISTINCT FROM OLD.codigo THEN
      NEW.codigo_grupo := NEW.codigo;
    ELSE
      NEW.codigo := NEW.codigo_grupo;
    END IF;
    IF NEW.numero_semestre IS DISTINCT FROM OLD.numero_semestre THEN
      NEW.semestre := NEW.numero_semestre;
    ELSE
      NEW.numero_semestre := NEW.semestre;
    END IF;
  END IF;
  NEW.nombre := COALESCE(NEW.nombre, NEW.codigo);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sincronizar_grupo_compatibilidad ON grupos;
CREATE TRIGGER trg_sincronizar_grupo_compatibilidad
  BEFORE INSERT OR UPDATE ON grupos
  FOR EACH ROW EXECUTE FUNCTION sincronizar_grupo_compatibilidad();

COMMIT;
