-- App Unificada UAE - esquema PostgreSQL para Supabase
-- Ejecutar en un proyecto de desarrollo. No incluye credenciales ni datos reales.

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_completo VARCHAR(150) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol VARCHAR(40) NOT NULL,
  semestre SMALLINT,
  grupo VARCHAR(20),
  CONSTRAINT chk_usuario_email CHECK (email ~* '^[A-Za-z0-9._%+-]+@uae[.]edu[.]mx$'),
  CONSTRAINT chk_usuario_semestre CHECK (semestre IS NULL OR semestre BETWEEN 1 AND 20)
);

CREATE TABLE IF NOT EXISTS categorias (
  id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS productos (
  id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria BIGINT NOT NULL REFERENCES categorias(id_categoria),
  nombre VARCHAR(150) NOT NULL,
  precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

CREATE TABLE IF NOT EXISTS pedidos (
  id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
  fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now(),
  estado VARCHAR(30) NOT NULL DEFAULT 'Pendiente',
  CONSTRAINT chk_pedido_estado CHECK (estado IN ('Pendiente', 'En preparacion', 'Listo', 'Entregado'))
);

CREATE TABLE IF NOT EXISTS detalles_pedido (
  id_pedido BIGINT NOT NULL REFERENCES pedidos(id_pedido) ON DELETE CASCADE,
  id_producto BIGINT NOT NULL REFERENCES productos(id_producto),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
  PRIMARY KEY (id_pedido, id_producto)
);

CREATE TABLE IF NOT EXISTS horarios_clases (
  id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  materia VARCHAR(150) NOT NULL,
  aula VARCHAR(50) NOT NULL,
  dia_semana VARCHAR(12) NOT NULL CHECK (dia_semana IN ('Lunes', 'Martes', 'Miercoles', 'Jueves', 'Viernes', 'Sabado', 'Domingo')),
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL CHECK (hora_fin > hora_inicio),
  semestre SMALLINT NOT NULL CHECK (semestre BETWEEN 1 AND 20),
  grupo VARCHAR(20) NOT NULL,
  id_profesor BIGINT NOT NULL REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS rutas_transporte (
  id_ruta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_ruta VARCHAR(150) NOT NULL,
  horario_salida TIME NOT NULL,
  estatus VARCHAR(20) NOT NULL DEFAULT 'Activa' CHECK (estatus IN ('Activa', 'Inactiva', 'POR_CONFIRMAR'))
);

CREATE TABLE IF NOT EXISTS puntos_parada (
  id_punto_parada BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ruta BIGINT NOT NULL REFERENCES rutas_transporte(id_ruta) ON DELETE CASCADE,
  orden SMALLINT NOT NULL CHECK (orden > 0),
  nombre VARCHAR(150) NOT NULL,
  hora_estimada TIME,
  UNIQUE (id_ruta, orden)
);

CREATE TABLE IF NOT EXISTS confirmaciones_transporte (
  id_confirmacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ruta BIGINT NOT NULL REFERENCES rutas_transporte(id_ruta),
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
  fecha_salida DATE NOT NULL,
  fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id_ruta, id_usuario, fecha_salida)
);

CREATE TABLE IF NOT EXISTS ubicaciones_unidad (
  id_ubicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ruta BIGINT NOT NULL REFERENCES rutas_transporte(id_ruta),
  unidad VARCHAR(80) NOT NULL,
  latitud NUMERIC(9,6) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
  longitud NUMERIC(9,6) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
  registrado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS anuncios (
  id_anuncio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(150) NOT NULL,
  contenido TEXT NOT NULL,
  categoria VARCHAR(100) NOT NULL,
  fecha_publicacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  id_autor BIGINT NOT NULL REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS votaciones (
  id_votacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(150) NOT NULL,
  descripcion TEXT NOT NULL,
  fecha_inicio TIMESTAMPTZ NOT NULL,
  fecha_fin TIMESTAMPTZ NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT chk_fechas_votacion CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE IF NOT EXISTS opciones_votacion (
  id_opcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_votacion BIGINT NOT NULL REFERENCES votaciones(id_votacion) ON DELETE CASCADE,
  texto VARCHAR(255) NOT NULL,
  UNIQUE (id_votacion, id_opcion)
);

CREATE TABLE IF NOT EXISTS votos_usuarios (
  id_votacion BIGINT NOT NULL REFERENCES votaciones(id_votacion) ON DELETE CASCADE,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
  id_opcion BIGINT NOT NULL,
  PRIMARY KEY (id_votacion, id_usuario),
  FOREIGN KEY (id_votacion, id_opcion)
    REFERENCES opciones_votacion(id_votacion, id_opcion)
);

-- RBAC ampliable: un usuario puede tener más de un rol (por ejemplo ESTUDIANTE + CCE).
CREATE TABLE IF NOT EXISTS roles (
  id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(40) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS usuario_roles (
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  id_rol BIGINT NOT NULL REFERENCES roles(id_rol) ON DELETE CASCADE,
  PRIMARY KEY (id_usuario, id_rol)
);
