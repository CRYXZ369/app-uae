-- Modelo académico normalizado para App Unificada UAE.
-- Requiere haber aplicado 01_ddl_app_unificada_uae_postgres.sql.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS carreras (
  id_carrera BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(10) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL UNIQUE,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS semestres (
  numero SMALLINT PRIMARY KEY CHECK (numero BETWEEN 1 AND 7),
  nombre VARCHAR(20) NOT NULL UNIQUE,
  tiene_taller_semanal BOOLEAN NOT NULL,
  CONSTRAINT chk_semestre_taller
    CHECK (tiene_taller_semanal = (numero BETWEEN 1 AND 6))
);

CREATE TABLE IF NOT EXISTS grupos (
  id_grupo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_carrera BIGINT NOT NULL REFERENCES carreras(id_carrera),
  numero_semestre SMALLINT NOT NULL REFERENCES semestres(numero),
  codigo VARCHAR(12) NOT NULL,
  nombre VARCHAR(30) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_grupo_carrera_semestre_codigo
    UNIQUE (id_carrera, numero_semestre, codigo),
  CONSTRAINT uq_grupo_contexto
    UNIQUE (id_grupo, id_carrera, numero_semestre)
);

CREATE TABLE IF NOT EXISTS materias (
  id_materia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(24) NOT NULL UNIQUE,
  id_carrera BIGINT NOT NULL REFERENCES carreras(id_carrera),
  numero_semestre SMALLINT NOT NULL REFERENCES semestres(numero),
  nombre VARCHAR(120) NOT NULL,
  CONSTRAINT uq_materia_carrera_semestre_nombre
    UNIQUE (id_carrera, numero_semestre, nombre),
  CONSTRAINT uq_materia_contexto
    UNIQUE (id_materia, id_carrera, numero_semestre)
);

CREATE TABLE IF NOT EXISTS docentes (
  id_docente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(24) NOT NULL UNIQUE,
  nombre_completo VARCHAR(150) NOT NULL,
  id_usuario BIGINT UNIQUE REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS aulas (
  id_aula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(80) NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS talleres (
  id_taller BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  orden SMALLINT NOT NULL UNIQUE CHECK (orden BETWEEN 1 AND 6),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE usuarios
  ADD COLUMN IF NOT EXISTS id_grupo BIGINT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'fk_usuarios_grupo_academico'
      AND conrelid = 'usuarios'::regclass
  ) THEN
    ALTER TABLE usuarios
      ADD CONSTRAINT fk_usuarios_grupo_academico
      FOREIGN KEY (id_grupo) REFERENCES grupos(id_grupo)
      ON DELETE SET NULL;
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS ix_usuarios_grupo_academico
  ON usuarios(id_grupo);

CREATE TABLE IF NOT EXISTS horarios_academicos (
  id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo BIGINT NOT NULL,
  id_carrera BIGINT NOT NULL,
  numero_semestre SMALLINT NOT NULL,
  id_materia BIGINT REFERENCES materias(id_materia),
  id_taller BIGINT REFERENCES talleres(id_taller),
  id_docente BIGINT NOT NULL REFERENCES docentes(id_docente),
  id_aula BIGINT NOT NULL REFERENCES aulas(id_aula),
  dia_semana VARCHAR(10) NOT NULL
    CHECK (dia_semana IN ('Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes')),
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  periodo TSRANGE GENERATED ALWAYS AS (
    tsrange(
      CASE dia_semana
        WHEN 'Lunes' THEN DATE '2000-01-03'
        WHEN 'Martes' THEN DATE '2000-01-04'
        WHEN 'Miércoles' THEN DATE '2000-01-05'
        WHEN 'Jueves' THEN DATE '2000-01-06'
        WHEN 'Viernes' THEN DATE '2000-01-07'
      END + hora_inicio,
      CASE dia_semana
        WHEN 'Lunes' THEN DATE '2000-01-03'
        WHEN 'Martes' THEN DATE '2000-01-04'
        WHEN 'Miércoles' THEN DATE '2000-01-05'
        WHEN 'Jueves' THEN DATE '2000-01-06'
        WHEN 'Viernes' THEN DATE '2000-01-07'
      END + hora_fin,
      '[)'
    )
  ) STORED,
  CONSTRAINT fk_horario_grupo_contexto
    FOREIGN KEY (id_grupo, id_carrera, numero_semestre)
    REFERENCES grupos(id_grupo, id_carrera, numero_semestre),
  CONSTRAINT fk_horario_materia_contexto
    FOREIGN KEY (id_materia, id_carrera, numero_semestre)
    REFERENCES materias(id_materia, id_carrera, numero_semestre),
  CONSTRAINT chk_horario_una_actividad
    CHECK (num_nonnulls(id_materia, id_taller) = 1),
  CONSTRAINT chk_horario_ventana_academica
    CHECK (
      hora_inicio >= TIME '08:00'
      AND hora_fin <= TIME '15:00'
      AND hora_fin > hora_inicio
    ),
  CONSTRAINT chk_horario_duracion
    CHECK (
      (id_materia IS NOT NULL
        AND hora_fin - hora_inicio BETWEEN INTERVAL '2 hours' AND INTERVAL '4 hours')
      OR
      (id_taller IS NOT NULL
        AND hora_fin - hora_inicio = INTERVAL '1 hour')
    ),
  CONSTRAINT uq_horario_grupo_inicio
    UNIQUE (id_grupo, dia_semana, hora_inicio),
  CONSTRAINT ex_horario_sin_choque_grupo
    EXCLUDE USING gist (id_grupo WITH =, periodo WITH &&),
  CONSTRAINT ex_horario_sin_choque_docente
    EXCLUDE USING gist (id_docente WITH =, periodo WITH &&),
  CONSTRAINT ex_horario_sin_choque_aula
    EXCLUDE USING gist (id_aula WITH =, periodo WITH &&)
);

CREATE INDEX IF NOT EXISTS ix_horarios_academicos_grupo_dia
  ON horarios_academicos(id_grupo, dia_semana, hora_inicio);

CREATE INDEX IF NOT EXISTS ix_horarios_academicos_docente_dia
  ON horarios_academicos(id_docente, dia_semana, hora_inicio);

CREATE OR REPLACE FUNCTION validar_taller_por_semestre()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.id_taller IS NOT NULL AND NEW.numero_semestre NOT BETWEEN 1 AND 6 THEN
    RAISE EXCEPTION 'Los talleres semanales solo aplican del semestre 1 al 6.';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_taller_por_semestre
  ON horarios_academicos;

CREATE TRIGGER trg_validar_taller_por_semestre
  BEFORE INSERT OR UPDATE OF id_taller, numero_semestre
  ON horarios_academicos
  FOR EACH ROW
  EXECUTE FUNCTION validar_taller_por_semestre();

