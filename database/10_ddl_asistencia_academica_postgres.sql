-- Registro de asistencia por sesión del horario para el MVP académico.
-- Requiere 03_ddl_academico_postgres.sql y los horarios de demostración.

CREATE TABLE IF NOT EXISTS asistencias_academicas (
  id_asistencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_horario BIGINT NOT NULL REFERENCES horarios_academicos(id_horario)
    ON DELETE CASCADE,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario)
    ON DELETE CASCADE,
  fecha_clase DATE NOT NULL,
  estado VARCHAR(20) NOT NULL
    CHECK (estado IN ('PRESENTE', 'RETARDO', 'FALTA', 'JUSTIFICADO')),
  registrada_por BIGINT REFERENCES usuarios(id_usuario)
    ON DELETE SET NULL,
  registrada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_asistencia_horario_estudiante_fecha
    UNIQUE (id_horario, id_usuario, fecha_clase)
);

CREATE INDEX IF NOT EXISTS ix_asistencia_estudiante_fecha
  ON asistencias_academicas(id_usuario, fecha_clase DESC);

CREATE OR REPLACE FUNCTION validar_asistencia_academica()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_grupo BIGINT;
  v_docente_usuario BIGINT;
  v_dia VARCHAR(10);
BEGIN
  SELECT h.id_grupo, d.id_usuario, h.dia_semana
    INTO v_grupo, v_docente_usuario, v_dia
  FROM horarios_academicos h
  JOIN docentes d ON d.id_docente = h.id_docente
  WHERE h.id_horario = NEW.id_horario;

  IF v_grupo IS NULL OR NOT EXISTS (
    SELECT 1 FROM usuarios u
    JOIN usuario_roles ur ON ur.id_usuario = u.id_usuario
    JOIN roles r ON r.id_rol = ur.id_rol
    WHERE u.id_usuario = NEW.id_usuario
      AND u.id_grupo = v_grupo AND u.activo
      AND r.codigo = 'ESTUDIANTE' AND r.activo
  ) THEN
    RAISE EXCEPTION 'El estudiante debe pertenecer al grupo de la sesión.';
  END IF;

  IF extract(isodow FROM NEW.fecha_clase)::INTEGER <> (CASE v_dia
      WHEN 'Lunes' THEN 1 WHEN 'Martes' THEN 2 WHEN 'Miércoles' THEN 3
      WHEN 'Jueves' THEN 4 WHEN 'Viernes' THEN 5 END) THEN
    RAISE EXCEPTION 'La fecha no coincide con el día programado de la clase.';
  END IF;

  IF NEW.registrada_por IS NOT NULL AND (
    v_docente_usuario IS NULL OR NEW.registrada_por <> v_docente_usuario OR NOT EXISTS (
      SELECT 1 FROM usuario_roles ur JOIN roles r ON r.id_rol = ur.id_rol
      WHERE ur.id_usuario = NEW.registrada_por
        AND r.codigo = 'DOCENTE' AND r.activo
    )
  ) THEN
    RAISE EXCEPTION 'Solo el docente asignado puede registrar asistencia.';
  END IF;

  NEW.registrada_en := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_asistencia_academica
  ON asistencias_academicas;
CREATE TRIGGER trg_validar_asistencia_academica
  BEFORE INSERT OR UPDATE ON asistencias_academicas
  FOR EACH ROW EXECUTE FUNCTION validar_asistencia_academica();

COMMENT ON TABLE asistencias_academicas IS
  'Registro académico de asistencia por horario; los estados son datos internos del MVP.';
